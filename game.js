  function ενημέρωσηΣωματιδίων(dt) {
    Κ.σωματίδια = Κ.σωματίδια.filter((σ) => {
      σ.ζωή -= dt / σ.διάρκεια;
      σ.vy += (σ.είδος === 'κομφετί' ? 520 : 900) * dt;
      σ.vx *= σ.είδος === 'κομφετί' ? 0.985 : 0.96;
      σ.x += σ.vx * dt;
      σ.y += σ.vy * dt;
      σ.περιστροφή += σ.ταχύτηταΠεριστροφής * dt;
      return σ.ζωή > 0;
    });
  }

