  // Δίχτυ με κυματισμό όταν μπαίνει γκολ
  function μετατόπισηΔιχτυού(x, y, χρόνος) {
    let τιμή = 0;
    for (const κ of Κ.κυματισμοί) {
      const ηλικία = χρόνος - κ.χρόνος;
      if (ηλικία < 0) continue;
      const απόσταση2 = (x - κ.x) ** 2 + (y - κ.y) ** 2;
      τιμή += κ.ένταση * Math.exp(-απόσταση2 / 0.9) * Math.exp(-ηλικία * 2.6) * Math.cos(ηλικία * 16);
    }
    return τιμή;
  }

  function ζωγράφισεΔίχτυ(c, χρόνος) {
    const ΜΠ = ΓΗΠΕΔΟ.μισόΠλάτος, Υ = ΓΗΠΕΔΟ.ύψος, zΓ = ΓΗΠΕΔΟ.zΓραμμής, zΔ = ΓΗΠΕΔΟ.zΔιχτυού;
    const ύψοςΠίσω = 1.9;
    // Σημείο της πίσω επιφάνειας με κυματισμό
    const πίσω = (x, y) => προβολή(x, y, zΔ + μετατόπισηΔιχτυού(x, y, χρόνος));

    // Σκούρο εσωτερικό
    c.fillStyle = 'rgba(2,6,14,0.55)';
    c.beginPath();
    let α = πίσω(-ΜΠ, 0); c.moveTo(α.x, α.y);
    α = πίσω(ΜΠ, 0); c.lineTo(α.x, α.y);
    α = πίσω(ΜΠ, ύψοςΠίσω); c.lineTo(α.x, α.y);
    α = πίσω(-ΜΠ, ύψοςΠίσω); c.lineTo(α.x, α.y);
    c.closePath();
    c.fill();

    c.strokeStyle = 'rgba(235,245,255,0.30)';
    c.lineWidth = Math.max(0.6, προβολή(0, 0, zΔ).κ * 0.012);
    const στήλες = 26, γραμμές = 9;

    // Πίσω επιφάνεια
    for (let i = 0; i <= στήλες; i++) {
      const x = -ΜΠ + (2 * ΜΠ * i) / στήλες;
      c.beginPath();
      for (let j = 0; j <= γραμμές; j++) {
        const π = πίσω(x, (ύψοςΠίσω * j) / γραμμές);
        if (j === 0) c.moveTo(π.x, π.y); else c.lineTo(π.x, π.y);
      }
      c.stroke();
    }
    for (let j = 0; j <= γραμμές; j++) {
      const y = (ύψοςΠίσω * j) / γραμμές;
      c.beginPath();
      for (let i = 0; i <= στήλες; i++) {
        const π = πίσω(-ΜΠ + (2 * ΜΠ * i) / στήλες, y);
        if (i === 0) c.moveTo(π.x, π.y); else c.lineTo(π.x, π.y);
      }
      c.stroke();
    }

    // Οροφή & πλαϊνά
    const βήματα = 8;
    for (let i = 0; i <= βήματα; i++) {
      const τ = i / βήματα;
      const z = zΓ + (zΔ - zΓ) * τ;
      const y = Υ + (ύψοςΠίσω - Υ) * τ;
      const α1 = προβολή(-ΜΠ, y, z), α2 = προβολή(ΜΠ, y, z);
      c.beginPath(); c.moveTo(α1.x, α1.y); c.lineTo(α2.x, α2.y); c.stroke();
      const β1 = προβολή(-ΜΠ, 0, z), β2 = προβολή(ΜΠ, 0, z);
      c.beginPath(); c.moveTo(α1.x, α1.y); c.lineTo(β1.x, β1.y); c.stroke();
      c.beginPath(); c.moveTo(α2.x, α2.y); c.lineTo(β2.x, β2.y); c.stroke();
    }
    for (let i = 0; i <= στήλες; i += 2) {
      const x = -ΜΠ + (2 * ΜΠ * i) / στήλες;
      const α1 = προβολή(x, Υ, zΓ), α2 = πίσω(x, ύψοςΠίσω);
      c.beginPath(); c.moveTo(α1.x, α1.y); c.lineTo(α2.x, α2.y); c.stroke();
    }
    for (let j = 0; j <= 5; j++) {
      const y = (Υ * j) / 5;
      [-ΜΠ, ΜΠ].forEach((x) => {
        const α1 = προβολή(x, y, zΓ), α2 = πίσω(x, Math.min(y, ύψοςΠίσω));
        c.beginPath(); c.moveTo(α1.x, α1.y); c.lineTo(α2.x, α2.y); c.stroke();
      });
    }
  }

