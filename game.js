  function απόδοση() {
    const { W, H, dpr } = Σκηνή;
    const χρόνος = Κ.χρόνοςΚόσμου;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, W, H);

    // Κάμερα: ζουμ προς το τέρμα και κούνημα
    const κέντροΤέρματος = προβολή(0, 1.1, ΓΗΠΕΔΟ.zΓραμμής);
    const κ = Κ.κούνημα * Κ.κούνημα * 14;
    ctx.save();
    ctx.translate(κέντροΤέρματος.x, κέντροΤέρματος.y);
    ctx.scale(Κ.ζουμ, Κ.ζουμ);
    ctx.translate(-κέντροΤέρματος.x + τυχαίο(-κ, κ), -κέντροΤέρματος.y + τυχαίο(-κ, κ));

    if (στατικόΦόντο) ctx.drawImage(στατικόΦόντο, 0, 0, W, H);
    ζωγράφισεΠινακίδες(ctx, performance.now() / 1000);

    // Λίστα αντικειμένων ταξινομημένη κατά βάθος (πιο μακρινά πρώτα)
    const αντικείμενα = [];
    αντικείμενα.push({ z: ΓΗΠΕΔΟ.zΔιχτυού, ζωγράφισε: () => ζωγράφισεΔίχτυ(ctx, χρόνος) });
    αντικείμενα.push({ z: ΓΗΠΕΔΟ.zΓραμμής, ζωγράφισε: () => ζωγράφισεΔοκάρια(ctx) });

    const τρ = Κ.τερματοφύλακας;
    αντικείμενα.push({
      z: ΓΗΠΕΔΟ.zΤερματοφύλακα,
      ζωγράφισε: () => {
        σκιάΠαίκτη(ctx, τρ.x, ΓΗΠΕΔΟ.zΤερματοφύλακα, Math.abs(τρ.θ) > 0.6 ? 1.1 : 0.55, 0.45);
        ζωγράφισεΣτοΚόσμο(ctx, τρ.x, τρ.y, ΓΗΠΕΔΟ.zΤερματοφύλακα, ΧΑΡΑΚΤΗΡΕΣ.τερματοφύλακας, πόζαΤερματοφύλακα(τρ, χρόνος));
      },
    });

    const α = Κ.αμυντικός;
    if (α.ενεργός) {
      αντικείμενα.push({
        z: ΓΗΠΕΔΟ.zΑμυντικού,
        ζωγράφισε: () => {
          σκιάΠαίκτη(ctx, α.x, ΓΗΠΕΔΟ.zΑμυντικού, 0.6, 0.5 / (1 + α.ύψος));
          ζωγράφισεΣτοΚόσμο(ctx, α.x, 1.0 + α.ύψος, ΓΗΠΕΔΟ.zΑμυντικού, ΧΑΡΑΚΤΗΡΕΣ.αμυντικός, πόζαΑμυντικού(χρόνος));
        },
      });
    }

    const ε = Κ.εκτελεστής;
    αντικείμενα.push({
      z: ε.z,
      ζωγράφισε: () => {
        σκιάΠαίκτη(ctx, ε.x, ε.z, 0.55, 0.5);
        // Ξεθωριάζει μετά την κλωτσιά για να φαίνεται καθαρά η φάση στο τέρμα
        ζωγράφισεΣτοΚόσμο(ctx, ε.x, 1.0, ε.z, ΧΑΡΑΚΤΗΡΕΣ.εκτελεστής, πόζαΕκτελεστή(χρόνος), ε.αδιαφάνεια);
      },
    });

    αντικείμενα.push({
      z: Κ.μπάλα.z + 0.01,
      ζωγράφισε: () => { ζωγράφισεΊχνος(ctx); ζωγράφισεΜπάλα(ctx); },
    });

    αντικείμενα.sort((α1, α2) => α2.z - α1.z).forEach((α1) => α1.ζωγράφισε());

    ζωγράφισεΣτόχαστρο(ctx, χρόνος);
    ctx.restore();

    // Οθόνη: φώτα, σωματίδια, βινιέτα
    ζωγράφισεΦώταΚαιΦλας(ctx, χρόνος);
    ζωγράφισεΣωματίδια(ctx);

    const βινιέτα = ctx.createRadialGradient(W / 2, H * 0.5, Math.min(W, H) * 0.35, W / 2, H * 0.5, Math.max(W, H) * 0.8);
    βινιέτα.addColorStop(0, 'rgba(0,0,0,0)');
    βινιέτα.addColorStop(1, `rgba(0,0,0,${0.55 + (1 - Κ.κλίμακαΧρόνου) * 0.25})`);
    ctx.fillStyle = βινιέτα;
    ctx.fillRect(0, 0, W, H);
  }

