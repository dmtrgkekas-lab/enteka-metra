  function ενημέρωση(dtΠραγματικό) {
    // Ομαλή μετάβαση slow-motion και ζουμ
    Κ.κλίμακαΧρόνου += (Κ.στόχοςΚλίμακαςΧρόνου - Κ.κλίμακαΧρόνου) * Math.min(1, dtΠραγματικό * 12);
    Κ.ζουμ += (Κ.στόχοςΖουμ - Κ.ζουμ) * Math.min(1, dtΠραγματικό * 3);
    Κ.κούνημα = Math.max(0, Κ.κούνημα - dtΠραγματικό * 1.6);
    Κ.γκολΦλας = Math.max(0, Κ.γκολΦλας - dtΠραγματικό);

    const dt = dtΠραγματικό * Κ.κλίμακαΧρόνου;
    Κ.χρόνοςΚόσμου += dt;
    Κ.χρόνοςΦάσης += dt;

    // --- Αμυντικός ---
    const α = Κ.αμυντικός;
    if (α.ενεργός) {
      if (α.σχέδιο && Κ.βολή && Κ.φάση === 'πτήση') {
        // Βουτιά προς τη γραμμή της μπάλας
        const σ = α.σχέδιο;
        const χρόνος = Κ.βολή.χρόνος;
        const π = περιορισμός((χρόνος - σ.αντίδραση) / Math.max(0.05, σ.χρόνοςΔιέλευσης - σ.αντίδραση), 0, 1);
        const ε = ομαλήΈξοδος(π);
        α.x = γραμμική(σ.αρχικόX, σ.τελικόX, ε);
        α.ύψος = Math.sin(Math.min(1, π) * Math.PI * 0.75) * σ.ύψοςΆλματος;
        α.γωνία = σ.κλίση * ε;
      } else if (Κ.φάση === 'στόχευση' || Κ.φάση === 'φόρα') {
        α.είσοδος = Math.min(1, α.είσοδος + dt * 1.8);
        α.φάσηΠεριπολίας += dt;
        const περιπολία = θέσηΠεριπολίας(α.φάσηΠεριπολίας);
        const ε = ομαλήΈξοδος(α.είσοδος);
        α.x = γραμμική(α.πλευράΕισόδου * 8, περιπολία, ε);
        α.ύψος = Math.sin(α.είσοδος * Math.PI) * 0.9; // πετάγεται μπροστά με άλμα
        α.γωνία = (1 - ε) * -α.πλευράΕισόδου * 0.5;
      } else if (Κ.φάση === 'αποτέλεσμα') {
        α.ύψος = Math.max(0, α.ύψος - dt * 2.5);
        α.γωνία *= 0.94;
      }
    }

    // --- Τερματοφύλακας ---
    const τρ = Κ.τερματοφύλακας;
    if (Κ.βολή && τρ.σχέδιο) {
      const χρόνος = Κ.βολή.χρόνος;
      const σ = στάσηΤερματοφύλακα(τρ.σχέδιο, χρόνος);
      Object.assign(τρ, σ);
      // Μετά από βουτιά πέφτει στο έδαφος
      if (Κ.φάση === 'αποτέλεσμα' && Math.abs(τρ.θ) > 0.8) {
        const πτώση = περιορισμός((Κ.χρόνοςΦάσης - 0.15) / 0.35, 0, 1);
        τρ.y = γραμμική(τρ.y, 0.3, ομαλήΚαμπύλη(πτώση));
      }
      if (Κ.φάση === 'αποτέλεσμα' && τρ.χαρά > 0 && Κ.χρόνοςΦάσης > 0.9) {
        τρ.θ *= 0.85; τρ.y = γραμμική(τρ.y, 0.95, 0.1); τρ.χαρά = 1;
      }
    } else {
      // Λικνίζεται πάνω στη γραμμή
      τρ.x = Math.sin(Κ.χρόνοςΚόσμου * 1.6) * 0.28;
      τρ.y = 0.95;
      τρ.θ = 0;
      τρ.πρόοδος = 0;
    }

    // --- Διαφάνεια εκτελεστή ---
    const ε = Κ.εκτελεστής;
    const στόχοςΑδιαφάνειας = Κ.φάση === 'στόχευση' ? 0.9 : Κ.φάση === 'φόρα' ? 1 : (ε.πόζα === 'πανηγυρισμός' ? 0.75 : 0.32);
    ε.αδιαφάνεια += (στόχοςΑδιαφάνειας - ε.αδιαφάνεια) * Math.min(1, dtΠραγματικό * 6);

    // --- Φάσεις ---
    if (Κ.φάση === 'φόρα') {
      const π = Math.min(1, Κ.χρόνοςΦάσης / 0.62);
      Κ.εκτελεστής.κλωτσιά = π;
      Κ.εκτελεστής.x = γραμμική(-1.3, -0.38, ομαλήΚαμπύλη(π));
      Κ.εκτελεστής.z = γραμμική(-1.0, -0.32, ομαλήΚαμπύλη(π));
      if (π >= 1) κλωτσιά();
    } else if (Κ.φάση === 'πτήση') {
      const β = Κ.βολή;
      β.χρόνος += dt;
      Κ.εκτελεστής.κλωτσιά = Math.min(1, Κ.εκτελεστής.κλωτσιά + dt * 2.2);
      const τ = Math.min(β.χρόνος / β.διάρκεια, β.έκβαση.τΓεγονότος);
      const θ = θέσηΣτηνΤροχιά(β, τ);
      Object.assign(Κ.μπάλα, θ);
      Κ.μπάλα.περιστροφή += dt * (β.τύπος === 'φαλτσο' ? 26 : β.τύπος === 'πανενκα' ? -8 : 18);
      Κ.μπάλα.ίχνος.push({ ...θ });
      if (Κ.μπάλα.ίχνος.length > 18) Κ.μπάλα.ίχνος.shift();

      // Slow-motion πριν από "κρίσιμα" γεγονότα
      const υπόλοιπο = β.έκβαση.τΓεγονότος * β.διάρκεια - β.χρόνος;
      const κρίσιμο = ['απόκρουση', 'μπλοκ', 'δοκάρι', 'οριζόντιο', 'δοκάριΓκολ'].includes(β.έκβαση.είδος) || β.τύπος === 'πανενκα';
      if (κρίσιμο && υπόλοιπο < 0.2) Κ.στόχοςΚλίμακαςΧρόνου = 0.22;
      else if (υπόλοιπο < 0.12) Κ.στόχοςΚλίμακαςΧρόνου = 0.5;

      if (β.χρόνος >= β.έκβαση.τΓεγονότος * β.διάρκεια) εφαρμογήΓεγονότος();
    } else if (Κ.φάση === 'αποτέλεσμα') {
      Κ.εκτελεστής.κλωτσιά = Math.min(1, Κ.εκτελεστής.κλωτσιά + dt * 2.2);
      if (Κ.βολή) Κ.βολή.χρόνος += dt;
      ενημέρωσηΦυσικήςΜπάλας(dt);
      if (Κ.χρόνοςΦάσης > 0.35) Κ.στόχοςΚλίμακαςΧρόνου = 1;
      if (Κ.χρόνοςΦάσης > 2.0) {
        Κ.φάση = 'αναμονή';
        επόμενοΒήμα();
      }
    }

    ενημέρωσηΣωματιδίων(dtΠραγματικό);
  }

  function ενημέρωσηΦυσικήςΜπάλας(dt) {
    const μ = Κ.μπάλα;
    if (μ.λειτουργία !== 'φυσική') return;
    const υποβήματα = 3;
    const h = dt / υποβήματα;
    for (let i = 0; i < υποβήματα; i++) {
      μ.vy -= 9.8 * h;
      μ.x += μ.vx * h;
      μ.y += μ.vy * h;
      μ.z += μ.vz * h;

      // Έδαφος
      if (μ.y < ΓΗΠΕΔΟ.ακτίναΜπάλας) {
        μ.y = ΓΗΠΕΔΟ.ακτίναΜπάλας;
        μ.vy = Math.abs(μ.vy) > 0.8 ? -μ.vy * 0.45 : 0;
        μ.vx *= 0.82;
        μ.vz *= 0.82;
      }

      // Δίχτυ
      if (μ.μέσαΣτοΔίχτυ) {
        const όριοΠίσω = ΓΗΠΕΔΟ.zΔιχτυού - 0.25;
        if (μ.z > όριοΠίσω) {
          μ.z = όριοΠίσω;
          μ.vz = -μ.vz * 0.12;
          μ.vx *= 0.4;
          μ.vy *= 0.5;
          if (!μ.χτύπησεΔίχτυ) {
            μ.χτύπησεΔίχτυ = true;
            Κ.κυματισμοί.push({ x: μ.x, y: μ.y, χρόνος: Κ.χρόνοςΚόσμου, ένταση: 0.9 });
            πανηγυρισμόςΓκολ();
          }
        }
        const όριοΠλάι = ΓΗΠΕΔΟ.μισόΠλάτος - 0.15;
        if (Math.abs(μ.x) > όριοΠλάι && μ.z > ΓΗΠΕΔΟ.zΓραμμής) {
          μ.x = Math.sign(μ.x) * όριοΠλάι;
          μ.vx = -μ.vx * 0.2;
        }
        if (μ.y > ΓΗΠΕΔΟ.ύψος - 0.15 && μ.z > ΓΗΠΕΔΟ.zΓραμμής) {
          μ.y = ΓΗΠΕΔΟ.ύψος - 0.15;
          μ.vy = -Math.abs(μ.vy) * 0.2;
        }
      }
    }
    μ.περιστροφή += dt * (Math.hypot(μ.vx, μ.vz) * 3);
    μ.ίχνος.push({ x: μ.x, y: μ.y, z: μ.z });
    if (μ.ίχνος.length > 18) μ.ίχνος.shift();
    if (μ.ίχνος.length > 2 && Κ.χρόνοςΦάσης > 0.25) μ.ίχνος.shift();

    // Σβήνει όταν φύγει μακριά
    if (μ.z > 20 || μ.z < -3 || Math.abs(μ.x) > 14) μ.αδιαφάνεια = Math.max(0, μ.αδιαφάνεια - dt * 3);
    Κ.κυματισμοί = Κ.κυματισμοί.filter((κ) => Κ.χρόνοςΚόσμου - κ.χρόνος < 2.5);
  }

