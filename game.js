  // Θέση μπάλας κατά την τροχιά (τ: 0 → 1 από βούλα μέχρι γραμμή)
  function θέσηΣτηνΤροχιά(β, τ) {
    const s = Math.sin(Math.PI * τ);
    return {
      x: β.αρχή.x + (β.στόχος.x - β.αρχή.x) * τ + β.καμπύλη * β.πρόσημοΚαμπύλης * s,
      y: β.αρχή.y + (β.στόχος.y - β.αρχή.y) * τ + β.τόξο * s,
      z: β.αρχή.z + (β.στόχος.z - β.αρχή.z) * τ,
    };
  }

  // Ο τερματοφύλακας αποφασίζει τη στιγμή που χτυπιέται η μπάλα
  function σχέδιοΤερματοφύλακα(β, δ, αρχικό) {
    const τύπος = ΤΥΠΟΙ_ΣΟΥΤ[β.τύπος];
    const πιθανότηταΔιαβάσματος = δ.διάβασμα * τύπος.διάβασμαΧ;
    const πιθανότηταΝαΜείνει = Math.min(0.55, 0.08 + Κ.ιστορικό.πανένκες * 0.14);
    let στόχος, έναρξη, μένει = false;

    if (Math.random() < πιθανότηταΔιαβάσματος) {
      // Διάβασε σωστά τη γωνία
      στόχος = { x: β.στόχος.x + γκαουσιανό() * 0.3, y: β.στόχος.y + γκαουσιανό() * 0.25 };
      έναρξη = δ.αντίδραση;
      if (Math.abs(στόχος.x) < 0.9) μένει = true;
    } else if (Math.random() < πιθανότηταΝαΜείνει) {
      μένει = true;
      στόχος = { x: γκαουσιανό() * 0.2, y: 1.6 };
      έναρξη = 0.3;
    } else {
      // Μαντεύει με βάση τις προτιμήσεις του εκτελεστή
      const β0 = Κ.ιστορικό.στήλες;
      const σύνολο = β0[0] + β0[1] * 0.45 + β0[2];
      let ρ = Math.random() * σύνολο, στήλη;
      if ((ρ -= β0[0]) < 0) στήλη = -1;
      else if ((ρ -= β0[1] * 0.45) < 0) στήλη = 0;
      else στήλη = 1;
      if (στήλη === 0) {
        μένει = true;
        στόχος = { x: γκαουσιανό() * 0.3, y: τυχαίο(0.9, 1.9) };
      } else {
        στόχος = { x: στήλη * τυχαίο(1.7, 2.65), y: Math.random() < 0.6 ? τυχαίο(0.3, 0.8) : τυχαίο(1.3, 2.0) };
      }
      έναρξη = τυχαίο(0.03, 0.09);
    }

    const p0 = { x: αρχικό.x, y: 0.95 };
    let θ, τελικό;
    if (μένει) {
      θ = περιορισμός((στόχος.x - p0.x) * 0.3, -0.45, 0.45);
      τελικό = { x: στόχος.x * 0.75, y: Math.max(0.95, στόχος.y - 1.05) };
    } else {
      θ = περιορισμός(Math.atan2(στόχος.x - p0.x, στόχος.y - p0.y), -1.85, 1.85);
      const ux = Math.sin(θ), uy = Math.cos(θ);
      τελικό = { x: στόχος.x - ux * 1.15, y: Math.max(0.34, στόχος.y - uy * 1.15) };
    }
    const απόσταση = Math.hypot(τελικό.x - p0.x, τελικό.y - p0.y);
    const διάρκεια = 0.16 + απόσταση / δ.ταχύτητα;
    return { p0, τελικό, θ, έναρξη, διάρκεια, μένει };
  }

  // Στάση τερματοφύλακα σε χρόνο (δευτ.) μετά το χτύπημα
  function στάσηΤερματοφύλακα(σ, χρόνος) {
    if (!σ || χρόνος < σ.έναρξη) return { x: σ ? σ.p0.x : 0, y: 0.95, θ: 0, πρόοδος: 0 };
    const π = περιορισμός((χρόνος - σ.έναρξη) / σ.διάρκεια, 0, 1);
    const ε = ομαλήΈξοδος(π);
    const άλμα = σ.μένει ? Math.sin(π * Math.PI) * 0.12 : Math.sin(π * Math.PI) * 0.22;
    return {
      x: γραμμική(σ.p0.x, σ.τελικό.x, ε),
      y: γραμμική(σ.p0.y, σ.τελικό.y, ε) + άλμα,
      θ: γραμμική(0, σ.θ, ε),
      πρόοδος: π,
    };
  }

  function πιάνειΟΤερματοφύλακας(στάση, σημείο, εμβέλεια) {
    const ux = Math.sin(στάση.θ), uy = Math.cos(στάση.θ);
    const ax = στάση.x - ux * 0.95, ay = στάση.y - uy * 0.95;
    const bx = στάση.x + ux * 1.15, by = στάση.y + uy * 1.15;
    // Ο κορμός είναι πιο φαρδύς από τα χέρια
    const απόστασηΚορμού = απόστασηΑπόΤμήμα(σημείο.x, σημείο.y, ax, ay, στάση.x + ux * 0.4, στάση.y + uy * 0.4);
    const απόστασηΧεριών = απόστασηΑπόΤμήμα(σημείο.x, σημείο.y, ax, ay, bx, by);
    return Math.min(απόστασηΚορμού - 0.06, απόστασηΧεριών) <= εμβέλεια + ΓΗΠΕΔΟ.ακτίναΜπάλας * 0.5;
  }

  // Ο αμυντικός πετάγεται προς τη γραμμή της μπάλας
  function σχέδιοΑμυντικού(β, δ, θέσηX) {
    const κλάσμα = (ΓΗΠΕΔΟ.zΑμυντικού - β.αρχή.z) / (β.στόχος.z - β.αρχή.z);
    const σημείο = θέσηΣτηνΤροχιά(β, κλάσμα);
    const χρόνοςΔιέλευσης = β.διάρκεια * κλάσμα;
    const αντίδραση = 0.09;
    const διαθέσιμος = Math.max(0, χρόνοςΔιέλευσης - αντίδραση);
    const απόσταση = σημείο.x - θέσηX;
    const μετακίνηση = Math.sign(απόσταση) * Math.min(Math.abs(απόσταση), δ.αμυντικόςΤαχύτητα * διαθέσιμος);
    const τελικόX = θέσηX + μετακίνηση;
    const μπλοκάρει = Math.abs(σημείο.x - τελικόX) < 0.52 && σημείο.y < 2.15;
    return {
      αρχικόX: θέσηX, τελικόX, αντίδραση, χρόνοςΔιέλευσης, σημείο, μπλοκάρει,
      ύψοςΆλματος: περιορισμός(σημείο.y - 1.3, 0.15, 0.7),
      κλίση: περιορισμός(μετακίνηση * 0.45, -1.0, 1.0),
    };
  }

  // Υπολογίζει την έκβαση ήδη από τη στιγμή της κλωτσιάς
  function υπολογισμόςΈκβασης(β, δ) {
    const τύπος = ΤΥΠΟΙ_ΣΟΥΤ[β.τύπος];
    if (β.αμυντικός && β.αμυντικός.μπλοκάρει) {
      return { είδος: 'μπλοκ', τΓεγονότος: (ΓΗΠΕΔΟ.zΑμυντικού - β.αρχή.z) / (β.στόχος.z - β.αρχή.z) };
    }
    const τ = β.στόχος;
    const τΤερμ = (ΓΗΠΕΔΟ.zΤερματοφύλακα - β.αρχή.z) / (β.στόχος.z - β.αρχή.z);
    const στάση = στάσηΤερματοφύλακα(β.τερματοφύλακας, β.διάρκεια * τΤερμ);
    const σημείο = θέσηΣτηνΤροχιά(β, τΤερμ);
    const κοντάΣτοΤέρμα = Math.abs(σημείο.x) < ΓΗΠΕΔΟ.μισόΠλάτος + 0.25 && σημείο.y < ΓΗΠΕΔΟ.ύψος + 0.2;
    if (κοντάΣτοΤέρμα && πιάνειΟΤερματοφύλακας(στάση, σημείο, δ.εμβέλεια * τύπος.εμβέλειαΧ)) {
      return { είδος: 'απόκρουση', τΓεγονότος: τΤερμ };
    }
    const ρ = ΓΗΠΕΔΟ.ακτίναΜπάλας + ΓΗΠΕΔΟ.πάχοςΔοκαριού;
    const αx = Math.abs(τ.x);
    if (Math.abs(αx - ΓΗΠΕΔΟ.μισόΠλάτος) < ρ && τ.y < ΓΗΠΕΔΟ.ύψος + ρ * 0.5) {
      const μέσα = αx < ΓΗΠΕΔΟ.μισόΠλάτος && Math.random() < 0.45;
      return { είδος: μέσα ? 'δοκάριΓκολ' : 'δοκάρι', τΓεγονότος: 1 };
    }
    if (Math.abs(τ.y - ΓΗΠΕΔΟ.ύψος) < ρ && αx < ΓΗΠΕΔΟ.μισόΠλάτος + ρ) {
      return { είδος: 'οριζόντιο', τΓεγονότος: 1 };
    }
    if (αx < ΓΗΠΕΔΟ.μισόΠλάτος && τ.y < ΓΗΠΕΔΟ.ύψος) return { είδος: 'γκολ', τΓεγονότος: 1 };
    return { είδος: τ.y >= ΓΗΠΕΔΟ.ύψος ? 'πάνω' : 'άουτ', τΓεγονότος: 1 };
  }

  // Δημιουργεί ένα πλήρες σουτ: τροχιά, σχέδια αντιπάλων, έκβαση
  function δημιουργίαΒολής(σημάδι, κλειδίΤύπου, θέσηΤερματοφύλακα, θέσηΑμυντικού) {
    const τύπος = ΤΥΠΟΙ_ΣΟΥΤ[κλειδίΤύπου];
    const δ = τρέχουσαΔυσκολία();
    const σφάλμα = τύπος.σφάλμα;
    const στόχος = {
      x: σημάδι.x + γκαουσιανό() * σφάλμα,
      y: Math.max(0.12, σημάδι.y + γκαουσιανό() * σφάλμα * 0.8 + (κλειδίΤύπου === 'κανονια' ? 0.2 : 0)),
      z: ΓΗΠΕΔΟ.zΓραμμής,
    };
    const β = {
      τύπος: κλειδίΤύπου,
      αρχή: { x: 0, y: ΓΗΠΕΔΟ.ακτίναΜπάλας, z: 0 },
      στόχος,
      διάρκεια: τύπος.διάρκεια * τυχαίο(0.96, 1.04),
      τόξο: τύπος.τόξο,
      καμπύλη: τύπος.καμπύλη,
      πρόσημοΚαμπύλης: Math.abs(στόχος.x) > 0.4 ? Math.sign(στόχος.x) : (Math.random() < 0.5 ? -1 : 1),
      χρόνος: 0,
    };
    β.τερματοφύλακας = σχέδιοΤερματοφύλακα(β, δ, θέσηΤερματοφύλακα);
    β.αμυντικός = θέσηΑμυντικού !== null ? σχέδιοΑμυντικού(β, δ, θέσηΑμυντικού) : null;
    β.έκβαση = υπολογισμόςΈκβασης(β, δ);
    return β;
  }

