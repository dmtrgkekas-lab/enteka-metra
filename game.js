  function κλωτσιά() {
    const σημάδι = Κ.στόχευση.κλειδωμένη;
    const θέσηΑμυντικού = Κ.αμυντικός.ενεργός && Κ.αμυντικός.είσοδος >= 1 ? Κ.αμυντικός.x : null;
    const β = δημιουργίαΒολής(σημάδι, Κ.τύποςΣουτ, { x: Κ.τερματοφύλακας.x }, θέσηΑμυντικού);
    Κ.βολή = β;
    Κ.τερματοφύλακας.σχέδιο = β.τερματοφύλακας;
    Κ.αμυντικός.σχέδιο = β.αμυντικός;

    // Ιστορικό για να "μαθαίνει" ο τερματοφύλακας
    const στήλη = σημάδι.x < -1.2 ? 0 : σημάδι.x > 1.2 ? 2 : 1;
    Κ.ιστορικό.στήλες[στήλη] += 1;
    if (Κ.τύποςΣουτ === 'πανενκα') Κ.ιστορικό.πανένκες += 1;

    Κ.μπάλα.λειτουργία = 'τροχιά';
    Κ.εκτελεστής.πόζα = 'κλωτσιά';
    Κ.εκτελεστής.κλωτσιά = 0;
    Κ.φάση = 'πτήση';
    Κ.χρόνοςΦάσης = 0;
    Κ.στόχοςΖουμ = 1.16;

    const δύναμη = Κ.τύποςΣουτ === 'κανονια' ? 1.2 : Κ.τύποςΣουτ === 'πανενκα' ? 0.5 : 0.9;
    Ήχος.κλωτσιά(δύναμη);
    const π = προβολή(0, 0.05, 0);
    δημιουργίαΣωματιδίων(π.x, π.y, 14, 'γρασίδι');
    if (Κ.τύποςΣουτ === 'κανονια') Κ.κούνημα = 0.35;
  }

  // Εφαρμόζεται τη στιγμή του γεγονότος (απόκρουση, γκολ κλπ)
  function εφαρμογήΓεγονότος() {
    const β = Κ.βολή;
    const μ = Κ.μπάλα;
    const είδος = β.έκβαση.είδος;
    const τ = β.έκβαση.τΓεγονότος;
    const α1 = θέσηΣτηνΤροχιά(β, Math.max(0, τ - 0.02));
    const α2 = θέσηΣτηνΤροχιά(β, τ);
    const dtΔείγματος = β.διάρκεια * 0.02;
    μ.vx = (α2.x - α1.x) / dtΔείγματος;
    μ.vy = (α2.y - α1.y) / dtΔείγματος;
    μ.vz = (α2.z - α1.z) / dtΔείγματος;
    Object.assign(μ, { x: α2.x, y: α2.y, z: α2.z, λειτουργία: 'φυσική' });

    const σημείο = προβολή(μ.x, μ.y, μ.z);
    let γκολ = false;
    let κλειδίΜηνύματος = είδος;

    switch (είδος) {
      case 'γκολ':
      case 'δοκάριΓκολ':
        γκολ = true;
        μ.μέσαΣτοΔίχτυ = true;
        if (είδος === 'δοκάριΓκολ') {
          μ.vx = -Math.sign(μ.x) * 3.5;
          μ.vz = Math.max(4, μ.vz * 0.5);
          Ήχος.δοκάρι();
          Κ.κούνημα = 0.5;
        }
        if (είδος === 'γκολ' && β.τύπος === 'πανενκα') κλειδίΜηνύματος = 'γκολΠανένκα';
        break;
      case 'απόκρουση': {
        const στάση = στάσηΤερματοφύλακα(β.τερματοφύλακας, β.διάρκεια * τ);
        μ.vz = -Math.abs(μ.vz) * τυχαίο(0.25, 0.4);
        μ.vx = (μ.x - στάση.x) * 2.8 + τυχαίο(-1.5, 1.5);
        μ.vy = τυχαίο(2.5, 5);
        Ήχος.γάντια();
        δημιουργίαΣωματιδίων(σημείο.x, σημείο.y, 26, 'σπίθες');
        Κ.τερματοφύλακας.χαράΜετά = true;
        if (β.τύπος === 'πανενκα' && β.τερματοφύλακας.μένει) κλειδίΜηνύματος = 'απόκρουσηΠανένκα';
        break;
      }
      case 'μπλοκ':
        μ.vz = -Math.abs(μ.vz) * 0.28;
        μ.vy = τυχαίο(3.5, 5.5);
        μ.vx = τυχαίο(-3, 3);
        Ήχος.γάντια();
        Κ.κούνημα = 0.4;
        δημιουργίαΣωματιδίων(σημείο.x, σημείο.y, 30, 'σπίθες');
        break;
      case 'δοκάρι':
        μ.vx = -Math.sign(μ.x) * τυχαίο(2, 4);
        μ.vz = -Math.abs(μ.vz) * 0.35;
        μ.vy = τυχαίο(0.5, 2.5);
        Ήχος.δοκάρι();
        Κ.κούνημα = 0.5;
        δημιουργίαΣωματιδίων(σημείο.x, σημείο.y, 18, 'σπίθες');
        break;
      case 'οριζόντιο':
        μ.vz = -Math.abs(μ.vz) * 0.35;
        μ.vy = τυχαίο(3, 5);
        Ήχος.δοκάρι();
        Κ.κούνημα = 0.5;
        δημιουργίαΣωματιδίων(σημείο.x, σημείο.y, 18, 'σπίθες');
        break;
      default: // πάνω / άουτ: συνεχίζει την πορεία της
        break;
    }

    // Καταγραφή αποτελέσματος
    Κ.αποτελέσματαΓύρου.push(γκολ);
    if (γκολ) {
      Κ.συνολικάΓκολ += 1;
      Κ.σερί += 1;
    } else {
      Κ.σερί = 0;
    }

    // Ήχοι & αντιδράσεις
    if (!γκολ && είδος !== 'δοκάρι' && είδος !== 'οριζόντιο') Ήχος.απογοήτευση();
    if (!γκολ) {
      Κ.εκτελεστής.πόζα = 'λύπη';
      Κ.τερματοφύλακας.χαρά = (είδος === 'απόκρουση') ? 0.01 : 0;
      if (είδος !== 'απόκρουση') Ήχος.ιαχή(0.45, 1.4);
    }

    const υπότιτλος = περιγραφήΣουτ(β);
    εμφάνισηΜηνύματος(τυχαίοΣτοιχείο(ΜΗΝΥΜΑΤΑ[κλειδίΜηνύματος]), υπότιτλος, γκολ ? 'goal' : (είδος === 'πάνω' || είδος === 'άουτ' ? 'miss' : 'save'));
    ενημέρωσηHUD();

    Κ.φάση = 'αποτέλεσμα';
    Κ.χρόνοςΦάσης = 0;
    Κ.στόχοςΖουμ = γκολ ? 1.22 : 1.12;
    Ήχος.αγωνία(0.1);
  }

  function πανηγυρισμόςΓκολ() {
    Ήχος.δίχτυ();
    Ήχος.ιαχή(1, 2.8);
    Κ.γκολΦλας = 2.6;
    Κ.κούνημα = Math.max(Κ.κούνημα, 0.6);
    Κ.εκτελεστής.πόζα = 'πανηγυρισμός';
    const π = προβολή(Κ.μπάλα.x, Κ.μπάλα.y, Κ.μπάλα.z);
    δημιουργίαΣωματιδίων(π.x, π.y, 140, 'κομφετί');
  }

  function περιγραφήΣουτ(β) {
    const τ = β.στόχος;
    const πλευρά = τ.x < -1.2 ? 'αριστερά' : τ.x > 1.2 ? 'δεξιά' : 'στο κέντρο';
    const ύψος = τ.y < 0.8 ? 'χαμηλά' : τ.y > 1.7 ? 'ψηλά' : 'μεσαίο ύψος';
    return `${ΤΥΠΟΙ_ΣΟΥΤ[β.τύπος].όνομα} · ${ύψος} ${πλευρά}`;
  }

  function επόμενοΒήμα() {
    const γκολ = Κ.αποτελέσματαΓύρου.filter(Boolean).length;
    const ριγμένα = Κ.αποτελέσματαΓύρου.length;
    const υπόλοιπα = ΡΥΘΜΙΣΕΙΣ.πέναλτιΑνάΓύρο - ριγμένα;
    const πέρασε = γκολ >= ΡΥΘΜΙΣΕΙΣ.γκολΓιαΠρόκριση;
    const αποκλείστηκε = γκολ + υπόλοιπα < ΡΥΘΜΙΣΕΙΣ.γκολΓιαΠρόκριση;
    if (πέρασε || αποκλείστηκε || υπόλοιπα === 0) τέλοςΓύρου(πέρασε);
    else επαναφοράΓιαΣουτ();
  }

